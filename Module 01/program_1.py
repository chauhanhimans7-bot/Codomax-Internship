# Program 1: Variables and data types
name = "Dev"            # str
semester_year = 3       # int
score = 87.5            # float
is_intern = True        # bool

print("Name:", name, "| type:", type(name).__name__)
print("Year:", semester_year, "| type:", type(semester_year).__name__)
print("Score:", score, "| type:", type(score).__name__)
print("Intern:", is_intern, "| type:", type(is_intern).__name__)



'''
Output:
Name: Dev | type: str
Year: 3 | type: int
Score: 87.5 | type: float
Intern: True | type: bool
'''